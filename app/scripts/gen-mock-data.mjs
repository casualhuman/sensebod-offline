#!/usr/bin/env node
/*
 * Regenerates mock/data/generated.ts from the repository's real content:
 *   - content/agriculture-videos.csv  → the 64 livestock videos and their topics
 *   - illustrations/**.svg            → each drawing's own aria-label, used as alt text
 * Run from app/:  node scripts/gen-mock-data.mjs
 */
import { promises as fs } from 'node:fs';
import path from 'node:path';

const appDir = path.resolve(import.meta.dirname, '..');
const repo = path.resolve(appDir, '..');

function parseCsvLine(line) {
  const cells = [];
  let cell = '';
  let quoted = false;
  for (let i = 0; i < line.length; i += 1) {
    const ch = line[i];
    if (quoted) {
      if (ch === '"' && line[i + 1] === '"') {
        cell += '"';
        i += 1;
      } else if (ch === '"') quoted = false;
      else cell += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ',') {
      cells.push(cell);
      cell = '';
    } else cell += ch;
  }
  cells.push(cell);
  return cells;
}

/** "082 Quail housing - English-Medium.mp4" → "Quail housing" */
function titleFromFile(file) {
  let title = file.replace(/\.mp4$/i, '').replace(/_/g, ' ');
  title = title.replace(/[\s-]*(FINAL\s+)?(ENGLISH|English|ENG|SPANISH|HINDI)?\s*-?\s*Medium$/i, '');
  title = title.replace(/^\d{3}\s+/, '').replace(/^SLM\d+\s+/, '');
  return title.replace(/\s+-\s*$/, '').replace(/\s+/g, ' ').trim();
}

function languageFromFile(file) {
  if (/SPANISH/i.test(file)) return 'es';
  if (/HINDI/i.test(file)) return 'hi';
  return 'en';
}

async function walk(dir) {
  const out = [];
  for (const entry of await fs.readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await walk(full)));
    else if (entry.name.endsWith('.svg')) out.push(full);
  }
  return out.sort();
}

const csv = (await fs.readFile(path.join(repo, 'content/agriculture-videos.csv'), 'utf8')).trim().split(/\r?\n/).slice(1);
const videos = csv.map((line) => {
  const [file = '', topic = ''] = parseCsvLine(line);
  return { file, topic, title: titleFromFile(file), language: languageFromFile(file) };
});

const illustrationsDir = path.join(repo, 'illustrations');
const alts = {};
for (const file of await walk(illustrationsDir)) {
  const head = (await fs.readFile(file, 'utf8')).slice(0, 1500);
  const label = /<svg[^>]*\saria-label="([^"]*)"/.exec(head);
  const key = path.relative(illustrationsDir, file).split(path.sep).join('/').replace(/\.svg$/, '');
  alts[key] = label ? label[1].replace(/&amp;/g, '&').replace(/&quot;/g, '"').replace(/&#39;/g, "'") : '';
}

const banner = `/*
 * GENERATED by scripts/gen-mock-data.mjs. Do not edit by hand.
 * Sources: content/agriculture-videos.csv, illustrations/**.svg (aria-label).
 */
`;
const body = `${banner}
export interface AgricultureVideo {
  /** File name on the Pi, as listed in content/agriculture-videos.csv. */
  file: string;
  /** Topic from the CSV ("matched by title words — check by hand"). */
  topic: string;
  /** Title cleaned from the file name. */
  title: string;
  /** Narration language taken from the file name: en, es or hi. */
  language: string;
}

export const AGRICULTURE_VIDEOS: AgricultureVideo[] = ${JSON.stringify(videos, null, 2)};

/** Illustration key → the drawing's own description (its aria-label). */
export const ILLUSTRATION_ALTS: Record<string, string> = ${JSON.stringify(alts, null, 2)};
`;
await fs.writeFile(path.join(appDir, 'mock/data/generated.ts'), body);
console.log(`videos: ${videos.length}, illustrations: ${Object.keys(alts).length}, without alt: ${Object.values(alts).filter((a) => !a).length}`);
